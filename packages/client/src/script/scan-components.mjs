import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Get current file's directory in ESM
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const customComponentsDir = path.join(
    __dirname,
    '../components/custom-components',
);
const outputPath = path.join(
    __dirname,
    '../components/custom-components/registry.ts',
);

function scanComponents() {
    try {
        const directories = fs
            .readdirSync(customComponentsDir, { withFileTypes: true })
            .filter((dirent) => dirent.isDirectory())
            .map((dirent) => {
                const name = dirent.name;
                const label = name
                    .split('-')
                    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
                    .join(' ');

                // Try to read component properties
                let properties = [];
                try {
                    const componentPath = path.join(
                        customComponentsDir,
                        name,
                        'index.tsx',
                    );
                    const content = fs.readFileSync(componentPath, 'utf8');
                    const propsMatch = content.match(
                        /export const componentProperties = (\[[\s\S]*?\]);/,
                    );
                    if (propsMatch) {
                        properties = eval(`(${propsMatch[1]})`);
                    }
                } catch (e) {
                    console.warn(
                        `Warning: Could not read properties for ${name}`,
                    );
                }

                return {
                    value: `${name}/index`,
                    label,
                    properties,
                };
            });

        const fileContent = `
// Generated by scan-components.mjs
export interface ComponentProperty {
    name: string;
    type: string;
    default: any;
    description: string;
}

export interface ComponentOption {
    value: string;
    label: string;
    properties: ComponentProperty[];
}

export const componentRegistry: ComponentOption[] = ${JSON.stringify(
            directories,
            null,
            2,
        )};

export default componentRegistry;
`;

        fs.writeFileSync(outputPath, fileContent);
        console.log('Component registry updated successfully!');
        console.log('Found components:', directories);
    } catch (error) {
        console.error('Error scanning components:', error);
        process.exit(1);
    }
}

scanComponents();
