/** Check whether a table needs a browse / listing page. */
function needsBrowsePage(table: TableConfig): boolean {
	return (
		table.operations.includes("read") ||
		table.operations.includes("update") ||
		table.operations.includes("delete")
	);
}

function generateNavJs(state: FormBuilderState): string {
	const links: { label: string; href: string }[] = [
		{ label: "Home", href: "index.html" },
	];

	for (const table of state.tables) {
		// Show a "Create" link if the table has create
		if (table.operations.includes("create")) {
			links.push({
				label: `+ New ${table.table}`,
				href: `create-${table.table.toLowerCase()}.html`,
			});
		}
		// Show a "Records" link if the table has read, update, or delete
		if (needsBrowsePage(table)) {
			links.push({
				label: `${table.table} Records`,
				href: `read-${table.table.toLowerCase()}.html`,
			});
		}
		// Show a dedicated "Edit" link if the table has update
		if (table.operations.includes("update")) {
			links.push({
				label: `Edit ${table.table}`,
				href: `update-${table.table.toLowerCase()}.html`,
			});
		}
	}

	return `// Generated navigation
(function() {
    var NAV_LINKS = ${JSON.stringify(links, null, 4)};
    var nav = document.getElementById("main-nav");
    if (!nav) return;
    var current = window.location.pathname.split("/").pop() || "index.html";
    nav.innerHTML = NAV_LINKS.map(function(link) {
        var active = current === link.href ? ' class="active"' : "";
        return '<a href="' + link.href + '"' + active + '>' + link.label + '</a>';
    }).join("");
})();
`;
}

