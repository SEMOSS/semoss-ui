/** Determine which columns to show when browsing a table's records. */
function getReadableColumns(table: TableConfig): FieldConfig[] {
	// Prefer explicitly configured read fields
	if (table.fields.read && table.fields.read.length > 0) {
		return table.fields.read.filter((f) => f.visible);
	}
	// Fall back to other operation fields
	const fallbackOps: Array<keyof typeof table.fields> = [
		"update",
		"delete",
		"create",
	];
	for (const op of fallbackOps) {
		const f = table.fields[op];
		if (f && f.length > 0) {
			return f.filter((field) => field.visible);
		}
	}
	// Last resort: synthesize from raw table columns
	return table.columns.map((col, i) => ({
		columnName: col.column,
		label: col.column,
		widgetType: "text" as const,
		placeholder: "",
		required: false,
		visible: true,
		order: i,
		dbType: col.type,
	}));
}

function fieldToInputHtml(field: FieldConfig, idPrefix: string): string {
	const id = `${idPrefix}-${field.columnName}`;
	const req = field.required ? '<span class="required">*</span>' : "";
	const helpHtml = field.helpText
		? `\n    <span class="field-help">${field.helpText}</span>`
		: "";

	switch (field.widgetType) {
		case "textarea":
			return `<div class="form-group">
    <label for="${id}">${field.label}${req}</label>
    <textarea id="${id}" name="${field.columnName}" placeholder="${field.placeholder}"${field.required ? " required" : ""}>${field.defaultValue || ""}</textarea>${helpHtml}
</div>`;

		case "select": {
			const opts = (field.options || [])
				.map((o) => {
					const sel = o === field.defaultValue ? " selected" : "";
					return `<option value="${o}"${sel}>${o}</option>`;
				})
				.join("\n        ");
			return `<div class="form-group">
    <label for="${id}">${field.label}${req}</label>
    <select id="${id}" name="${field.columnName}"${field.required ? " required" : ""}>
        <option value="">Select...</option>
        ${opts}
    </select>${helpHtml}
</div>`;
		}

		case "checkbox": {
			const checkedVal = field.checkedValue || "1";
			const checked =
				field.defaultValue === "1" || field.defaultValue === "true"
					? " checked"
					: "";
			return `<div class="form-group">
    <div class="check-row">
        <input type="checkbox" id="${id}" name="${field.columnName}" value="${checkedVal}"${checked}>
        <label for="${id}">${field.label}${req}</label>
    </div>${helpHtml}
</div>`;
		}

		case "radio":
			return `<div class="form-group">
    <label>${field.label}${req}</label>
    ${(field.options || ["Yes", "No"])
		.map(
			(o, i) =>
				`<div class="check-row">
        <input type="radio" id="${id}-${i}" name="${field.columnName}" value="${o}"${o === field.defaultValue ? " checked" : ""}${i === 0 && field.required ? " required" : ""}>
        <label for="${id}-${i}">${o}</label>
    </div>`,
		)
		.join("\n    ")}${helpHtml}
</div>`;

		case "toggle": {
			const checkedVal = field.checkedValue || "1";
			const checked =
				field.defaultValue === "1" || field.defaultValue === "true"
					? " checked"
					: "";
			return `<div class="form-group">
    <div class="check-row">
        <label class="toggle-switch">
            <input type="checkbox" id="${id}" name="${field.columnName}" value="${checkedVal}"${checked}>
            <span class="toggle-slider"></span>
        </label>
        <label for="${id}">${field.label}${req}</label>
    </div>${helpHtml}
</div>`;
		}

		default: {
			const val = field.defaultValue
				? ` value="${field.defaultValue}"`
				: "";
			return `<div class="form-group">
    <label for="${id}">${field.label}${req}</label>
    <input type="${field.widgetType}" id="${id}" name="${field.columnName}" placeholder="${field.placeholder}"${val}${field.required ? " required" : ""}>${helpHtml}
</div>`;
		}
	}
}

function generateCreatePage(table: TableConfig): string {
	const fields = table.fields.create.filter((f) => f.visible);
	const formFields = fields
		.sort((a, b) => a.order - b.order)
		.map((f) => fieldToInputHtml(f, "create"))
		.join("\n");

	const collectValues = fields
		.map((f) => {
			if (f.widgetType === "checkbox" || f.widgetType === "toggle") {
				const cv = JSON.stringify(f.checkedValue || "1");
				const uv = JSON.stringify(f.uncheckedValue || "0");
				return `    const v_${f.columnName} = document.getElementById("create-${f.columnName}").checked ? ${cv} : ${uv};`;
			}
			if (f.widgetType === "radio") {
				return `    const v_${f.columnName} = (document.querySelector('input[name="${f.columnName}"]:checked') || {}).value || "";`;
			}
			return `    const v_${f.columnName} = document.getElementById("create-${f.columnName}").value;`;
		})
		.join("\n");

	const buildSqlParts = fields
		.map((f) => {
			if (f.widgetType === "number") {
				return `    vals.push(v_${f.columnName} !== "" && v_${f.columnName} !== null ? v_${f.columnName} : "NULL");`;
			}
			if (f.widgetType === "checkbox" || f.widgetType === "toggle") {
				return `    vals.push(!isNaN(v_${f.columnName}) ? v_${f.columnName} : "'" + String(v_${f.columnName}).replace(/'/g, "''") + "'");`;
			}
			return `    vals.push("'" + String(v_${f.columnName}).replace(/'/g, "''") + "'");`;
		})
		.join("\n");

	const sqlColumns = fields.map((f) => f.columnName).join(", ");

	return `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Create ${table.table}</title>
    <link rel="stylesheet" href="styles.css">
    <script src="app.js"></script>
</head>
<body>
<div class="app-container">
    <nav id="main-nav"></nav>

    <div class="card">
        <div class="card-title">Create ${table.table}</div>
        <div class="card-description">Add a new record to the ${table.table} table.</div>

        <div id="alert" class="alert"></div>

        <form id="create-form" onsubmit="handleCreate(event)">
${formFields}
            <button type="submit" class="btn btn-primary">
                Create Record <span id="spinner" class="spinner"></span>
            </button>
        </form>
    </div>
</div>

<script src="nav.js"></script>
<script>
async function handleCreate(e) {
    e.preventDefault();
    var spinner = document.getElementById("spinner");
    spinner.style.display = "inline-block";

${collectValues}

    var vals = [];
${buildSqlParts}

    try {
        var sql = "INSERT INTO ${table.table} (${sqlColumns}) VALUES (" + vals.join(", ") + ")";
        await commitDatabase(sql);
        showAlert("alert", "Record created successfully!", "success");
        document.getElementById("create-form").reset();
    } catch (err) {
        showAlert("alert", "Error: " + err.message, "error");
    } finally {
        spinner.style.display = "none";
    }
}
</script>
</body>
</html>
`;
}

