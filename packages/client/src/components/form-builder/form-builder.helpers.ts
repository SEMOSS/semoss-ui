export interface GeneratedFile {
	/** Relative path under portals/ */
	path: string;
	/** File content */
	content: string;
}

/**
 * Generate all files for the CODE app from the form builder state.
 */
export function generateFormAppFiles(state: FormBuilderState): GeneratedFile[] {
	const files: GeneratedFile[] = [
		{ path: "styles.css", content: generateStylesCss() },
		{ path: "app.js", content: generateAppJs(state) },
		{ path: "nav.js", content: generateNavJs(state) },
		{ path: "index.html", content: generateIndexHtml(state) },
	];

	for (const table of state.tables) {
		const ops = new Set(table.operations);

		if (ops.has("create")) {
			files.push({
				path: `create-${table.table.toLowerCase()}.html`,
				content: generateCreatePage(table),
			});
		}

		if (ops.has("update")) {
			files.push({
				path: `update-${table.table.toLowerCase()}.html`,
				content: generateUpdatePage(table),
			});
		}

		// Generate a single read/browse page that also handles delete via modal
		if (needsBrowsePage(table)) {
			files.push({
				path: `read-${table.table.toLowerCase()}.html`,
				content: generateReadPage(table),
			});
		}
	}

	return files;
}
