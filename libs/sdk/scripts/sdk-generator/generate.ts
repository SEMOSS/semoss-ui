/**
 * Generates the SDK's REST calls and Pixel catalog from the backend's OpenAPI document,
 * writing only what changed, or checking for drift without writing.
 */

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
	existsSync,
	mkdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { byName, canonicalJson } from "./order.ts";
import { emitPixelCatalog } from "./pixel.ts";
import { emitRestModules, planOperations } from "./rest.ts";
import { SpecError, validateDocument } from "./spec.ts";

/** Bumped whenever a change to the generator changes its output. */
export const GENERATOR_VERSION = 1;

/** The first line of every generated source file. */
export const GENERATED_HEADER =
	"// @generated by @semoss/sdk scripts/sdk-generator from the backend OpenAPI document. Do not edit.";

/** The manifest, relative to the generated folder. */
export const MANIFEST_FILE = "manifest.json";

/** What a generation run records about its output. */
export interface Manifest {
	generatorVersion: number;
	/** SHA-256 of the document with its keys sorted, so reformatting it does not change the hash. */
	specSha256: string;
	/** Generated source files relative to the generated folder, mapped to their SHA-256. */
	files: Record<string, string>;
}

/** Formats one file's content; `path` decides the language and the Biome settings. */
export type Formatter = (path: string, content: string) => string;

export interface GenerateOptions {
	/** The folder generated files are written to, normally `libs/sdk/src/generated`. */
	outDir: string;
	/** The backend OpenAPI document to read. It is not copied into the SDK. */
	openapi: string;
	/** Compare instead of writing. */
	check?: boolean;
	format: Formatter;
}

export interface GenerateResult {
	/** Files whose content differs from what is on disk (written, or reported by a check). */
	changed: string[];
	/** Obsolete generated files (deleted, or reported by a check). */
	removed: string[];
	/** Obsolete files left alone because they do not look generated. */
	kept: string[];
}

const sha256 = (content: string) =>
	createHash("sha256").update(content).digest("hex");

/** Runs the generator. Throws `SpecError` for an unusable document, leaving the output untouched. */
export function generate(options: GenerateOptions): GenerateResult {
	const { outDir, format } = options;
	const source = options.openapi;
	if (!existsSync(source)) {
		throw new SpecError(`${source} does not exist`);
	}

	let parsed: unknown;
	try {
		parsed = JSON.parse(readFileSync(source, "utf8"));
	} catch (error) {
		throw new SpecError(`${source} is not valid JSON: ${String(error)}`);
	}
	const doc = validateDocument(parsed);

	// Every file is built and formatted in memory before anything is written.
	const sources = new Map<string, string>([
		...emitRestModules(doc, planOperations(doc), GENERATED_HEADER),
		...emitPixelCatalog(doc, GENERATED_HEADER),
	]);

	const files = new Map<string, string>();
	const hashes: Record<string, string> = {};
	for (const [path, content] of [...sources].sort(([a], [b]) =>
		byName(a, b),
	)) {
		const formatted = format(join(outDir, path), `${content}\n`);
		files.set(path, formatted);
		hashes[path] = sha256(formatted);
	}

	const manifest: Manifest = {
		generatorVersion: GENERATOR_VERSION,
		specSha256: sha256(canonicalJson(doc)),
		files: hashes,
	};
	files.set(
		MANIFEST_FILE,
		format(
			join(outDir, MANIFEST_FILE),
			`${JSON.stringify(manifest, null, "\t")}\n`,
		),
	);

	const result: GenerateResult = { changed: [], removed: [], kept: [] };
	for (const [path, content] of files) {
		const target = join(outDir, path);
		const current = existsSync(target)
			? readFileSync(target, "utf8")
			: undefined;
		if (current !== content) {
			result.changed.push(path);
		}
	}

	for (const path of Object.keys(readManifest(outDir)?.files ?? {}).sort(
		byName,
	)) {
		if (files.has(path)) {
			continue;
		}
		const target = join(outDir, path);
		if (!existsSync(target)) {
			continue;
		}
		if (readFileSync(target, "utf8").startsWith(GENERATED_HEADER)) {
			result.removed.push(path);
		} else {
			result.kept.push(path);
		}
	}

	if (options.check) {
		return result;
	}

	for (const path of result.changed) {
		const target = join(outDir, path);
		mkdirSync(dirname(target), { recursive: true });
		writeFileSync(target, files.get(path) ?? "");
	}
	for (const path of result.removed) {
		rmSync(join(outDir, path));
	}
	return result;
}

/** Reads the manifest of the last run, if there is one. */
export function readManifest(outDir: string): Manifest | undefined {
	const path = join(outDir, MANIFEST_FILE);
	if (!existsSync(path)) {
		return undefined;
	}
	return JSON.parse(readFileSync(path, "utf8")) as Manifest;
}

/** Finds the repository root, where `biome.json` lives. */
export function findRepoRoot(from: string): string {
	let current = resolve(from);
	while (!existsSync(join(current, "biome.json"))) {
		const parent = dirname(current);
		if (parent === current) {
			throw new Error(`No biome.json above ${from}`);
		}
		current = parent;
	}
	return current;
}

/**
 * Formats with the repository's own Biome, so generated files pass `pnpm check`:
 * it applies the formatter and the safe fixes, such as sorting imports.
 */
export function createBiomeFormatter(repoRoot: string): Formatter {
	const biome = join(repoRoot, "node_modules", ".bin", "biome");
	return (path, content) => {
		const result = spawnSync(
			biome,
			[
				"check",
				"--write",
				`--stdin-file-path=${relative(repoRoot, path)}`,
			],
			{ cwd: repoRoot, input: content, encoding: "utf8" },
		);
		if (result.status !== 0 || !result.stdout) {
			throw new Error(
				`Biome could not format ${path}:\n${result.stderr || result.stdout}`,
			);
		}
		return result.stdout;
	};
}
