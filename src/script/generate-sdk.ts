import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import {
	mkdir,
	mkdtemp,
	readdir,
	readFile,
	rm,
	writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { delimiter, dirname, join, resolve } from "node:path";
import { parseArgs } from "node:util";
import { parseCatalog, stableJSON } from "./sdk-generator/contracts.ts";
import { isGeneratedPath, renderSDK } from "./sdk-generator/render-sdk.ts";
import { saveSyncRecord } from "./sdk-generator/sync.ts";

const root = resolve(import.meta.dirname, "../..");
const contractFile = "libs/sdk/contracts/operations.json";
const manifestFile = "libs/sdk/contracts/generated-files.json";
const selectionFile = join(import.meta.dirname, "sdk-operations.json");
const { values } = parseArgs({
	options: {
		semoss: { type: "string" },
		monolith: { type: "string" },
		check: { type: "boolean", default: false },
		"from-contracts": { type: "boolean", default: false },
		help: { type: "boolean", default: false },
	},
});

if (values.help) {
	console.log(
		"Usage: node src/script/generate-sdk.ts [--semoss PATH --monolith PATH] [--check]\n       node src/script/generate-sdk.ts --from-contracts [--check]\n\nLive generation needs JDK 21 and compiled SEMOSS/Monolith dependencies. Paths may\nalso come from SEMOSS_DIR / MONOLITH_DIR or sibling checkouts. --from-contracts\nreplays the checked-in neutral JSON without Java. --check never writes outputs.",
	);
} else {
	try {
		await generate();
	} catch (error) {
		console.error(error instanceof Error ? error.message : String(error));
		process.exitCode = 1;
	}
}

/** Generate, format and validate everything before changing any checked-in output. */
async function generate(): Promise<void> {
	const catalog = parseCatalog(
		values["from-contracts"]
			? await readFile(join(root, contractFile), "utf8")
			: await exportBackend(),
	);
	const rendered = renderSDK(catalog);
	const output = new Map<string, string>();
	const sources = new Map([
		...rendered,
		[contractFile, stableJSON(catalog)],
		[manifestFile, stableJSON([...rendered.keys()])],
	]);
	for (const [file, text] of sources) {
		if (
			file !== contractFile &&
			file !== manifestFile &&
			!isGeneratedPath(file)
		)
			throw new Error(`Invalid generated path: ${file}`);
		output.set(
			file,
			execFileSync(
				join(root, "node_modules/.bin/biome"),
				["format", `--stdin-file-path=${file}`],
				{ cwd: root, input: text, encoding: "utf8" },
			),
		);
	}
	const oldManifest: unknown = existsSync(join(root, manifestFile))
		? JSON.parse(await readFile(join(root, manifestFile), "utf8"))
		: [];
	if (
		!Array.isArray(oldManifest) ||
		oldManifest.some(
			(file) => typeof file !== "string" || !isGeneratedPath(file),
		)
	)
		throw new Error("Invalid generated-file manifest");
	const removed = oldManifest.filter((file: string) => !rendered.has(file));
	const packageManifest: unknown = JSON.parse(
		await readFile(join(root, "libs/sdk/package.json"), "utf8"),
	);
	if (
		!packageManifest ||
		typeof packageManifest !== "object" ||
		!("exports" in packageManifest) ||
		!packageManifest.exports ||
		typeof packageManifest.exports !== "object"
	)
		throw new Error("Missing SDK exports");
	for (const file of removed) {
		const declaration = file
			.replace("libs/sdk/src/", "./dist/types/")
			.replace(/\.ts$/, ".d.ts");
		if (
			Object.values(packageManifest.exports).some(
				(entry) =>
					entry &&
					typeof entry === "object" &&
					"types" in entry &&
					entry.types === declaration,
			)
		)
			throw new Error(
				`Remove the curated package export and build entry before removing ${file} from the selection.`,
			);
	}
	const changed: string[] = [];
	for (const [file, text] of output) {
		const current = existsSync(join(root, file))
			? await readFile(join(root, file), "utf8")
			: null;
		if (current !== text) changed.push(file);
		if (
			isGeneratedPath(file) &&
			current !== null &&
			!current.startsWith("// Generated by src/script/generate-sdk.ts.")
		)
			throw new Error(`Refusing to overwrite an authored file: ${file}`);
	}
	for (const file of removed) {
		if (
			existsSync(join(root, file)) &&
			!(await readFile(join(root, file), "utf8")).startsWith(
				"// Generated by src/script/generate-sdk.ts.",
			)
		)
			throw new Error(`Refusing to remove an authored file: ${file}`);
	}
	if (values.check) {
		if (changed.length || removed.length)
			throw new Error(
				`Generated SDK is out of date:\n${[...changed, ...removed].map((file) => `  ${file}`).join("\n")}\nRun generation without --check.`,
			);
		console.log(
			`Generated SDK matches ${catalog.operations.length} selected backend contracts${values["from-contracts"] ? " (snapshot replay)" : " (live sources)"}.`,
		);
		return;
	}
	for (const file of changed) {
		await mkdir(dirname(join(root, file)), { recursive: true });
		await writeFile(join(root, file), output.get(file) ?? "");
	}
	for (const file of removed) await rm(join(root, file), { force: true });
	// A check or snapshot replay does not establish a new backend sync time.
	// Write this last so a failed export/render/write retains the previous record.
	if (!values["from-contracts"]) await saveSyncRecord(root, catalog);
	console.log(
		`Generated ${rendered.size} SDK files from ${catalog.operations.length} selected contracts; ${changed.length} files changed, ${removed.length} removed.`,
	);
	if (!values["from-contracts"])
		console.log("Saved last backend sync to semoss-sync.json.");
}

/** Recompile the selected sources so annotations never come from a stale JAR. */
async function exportBackend(): Promise<string> {
	console.log(
		"Reading selected SEMOSS and Monolith contracts from current Java sources...",
	);
	const semoss = backendPath(
		values.semoss ?? process.env.SEMOSS_DIR,
		"Semoss",
	);
	const monolith = backendPath(
		values.monolith ?? process.env.MONOLITH_DIR,
		"Monolith",
	);
	const temporary = await mkdtemp(join(tmpdir(), "semoss-sdk-contracts-"));
	try {
		const classpath: string[] = [];
		for (const backend of [semoss, monolith]) {
			if (!existsSync(join(backend, "target/classes")))
				throw new Error(
					`Compile ${backend} with Maven first; target/classes is missing.`,
				);
			classpath.push(join(backend, "target/classes"));
			const dependencies = join(backend, "target/contract-classpath.txt");
			// Refresh the dependency list on every live read. This resolves dependencies
			// only; it never runs backend startup or tests.
			execFileSync(
				"mvn",
				[
					"-q",
					"-o",
					"dependency:build-classpath",
					`-Dmdep.outputFile=${dependencies}`,
				],
				{ cwd: backend, stdio: "inherit" },
			);
			classpath.push((await readFile(dependencies, "utf8")).trim());
		}
		const sourcepath = [join(semoss, "src"), join(monolith, "src")];
		const contractDirectory = join(semoss, "src/prerna/contract");
		const sources = (await readdir(contractDirectory))
			.filter((file) => file.endsWith(".java"))
			.sort()
			.map((file) => join(contractDirectory, file));
		sources.push(join(semoss, "src/prerna/reactor/AbstractReactor2.java"));
		const selection: unknown = JSON.parse(
			readFileSync(selectionFile, "utf8"),
		);
		if (
			!selection ||
			typeof selection !== "object" ||
			!("rest" in selection) ||
			!("pixels" in selection) ||
			!Array.isArray(selection.rest) ||
			!Array.isArray(selection.pixels)
		)
			throw new Error("Invalid operation selection");
		for (const item of selection.rest) {
			if (
				!item ||
				typeof item !== "object" ||
				!("resource" in item) ||
				!("application" in item)
			)
				throw new Error("Invalid REST selection");
			for (const name of [item.resource, item.application])
				sources.push(javaSource(monolith, name));
		}
		for (const name of selection.pixels)
			sources.push(javaSource(semoss, name));
		sources.push(
			join(import.meta.dirname, "sdk-generator/ExportContracts.java"),
		);
		const java = (binary: string): string =>
			process.env.JAVA_HOME
				? join(process.env.JAVA_HOME, "bin", binary)
				: binary;
		execFileSync(
			java("javac"),
			[
				"--release",
				"21",
				"-proc:none",
				"-encoding",
				"UTF-8",
				"-cp",
				classpath.join(delimiter),
				"-sourcepath",
				sourcepath.join(delimiter),
				"-d",
				temporary,
				...new Set(sources),
			],
			{ cwd: root, stdio: "inherit" },
		);
		const exported = join(temporary, "contracts.json");
		execFileSync(
			java("java"),
			[
				"-cp",
				[temporary, ...classpath].join(delimiter),
				"ExportContracts",
				selectionFile,
				exported,
			],
			{ cwd: temporary, stdio: "inherit" },
		);
		return await readFile(exported, "utf8");
	} finally {
		await rm(temporary, { recursive: true, force: true });
	}
}

function javaSource(backend: string, name: unknown): string {
	if (
		typeof name !== "string" ||
		!/^[A-Za-z_$][\w$]*(\.[A-Za-z_$][\w$]*)+$/.test(name)
	)
		throw new Error(`Invalid Java class name: ${String(name)}`);
	return join(backend, "src", `${name.replaceAll(".", "/")}.java`);
}

function backendPath(explicit: string | undefined, name: string): string {
	if (explicit) return resolve(explicit);
	let parent = root;
	while (dirname(parent) !== parent) {
		const candidate = join(parent, name);
		if (existsSync(join(candidate, "pom.xml"))) return candidate;
		parent = dirname(parent);
	}
	throw new Error(
		`Cannot locate ${name}. Pass --${name.toLowerCase()} PATH or set ${name.toUpperCase()}_DIR.`,
	);
}
