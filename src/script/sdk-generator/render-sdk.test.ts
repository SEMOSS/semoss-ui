const snapshot = readFileSync(
	new URL("../../../libs/sdk/contracts/operations.json", import.meta.url),
	"utf8",
);
const fresh = (): Catalog => parseCatalog(snapshot);
const pixel = (catalog: Catalog) => {
	const selected = catalog.operations.find(
		(operation) => operation.contract.kind === "PIXEL",
	);
	assert(selected);
	return selected;
};
const rest = (catalog: Catalog) => {
	const selected = catalog.operations.find(
		(operation) => operation.contract.kind === "REST",
	);
	assert(selected);
	return selected;
};
const type = (
	shape: TypeUse["shape"],
	options: Partial<Omit<TypeUse, "shape">> = {},
): TypeUse => ({
	shape,
	description: "",
	format: "",
	nullable: false,
	knowledge: "VERIFIED",
	reason: "",
	...options,
});
const string = type({ type: "scalar", kind: "STRING", values: [] });
const renderedPixels = (catalog: Catalog): string => {
	const result = renderSDK(catalog).get(
		"libs/sdk/src/lib/reactors/catalog.ts",
	);
	assert(result);
	return result;
};

test("live examples retain statuses, literal fields, required id and both invocation forms", () => {
	const catalog = fresh();
	assert.deepEqual(
		rest(catalog).contract.outputs.map((output) => output.status),
		[200, 503],
	);
	const files = renderSDK(catalog);
	const health = files.get("libs/sdk/src/api/health/health.ts") ?? "";
	assert.match(health, /GET \/health\/ready/);
	assert.match(health, /Promise<ReadyResponses\[200\]>/);
	assert.match(health, /503: ReadyType1/);
	assert.match(health, /"NOT_READY" \| "READY"/);
	assert.match(health, /"startupComplete": boolean/);
	assert.match(renderedPixels(catalog), /"id": PixelArgument<string>/);
	assert.match(renderedPixels(catalog), /\[PixelArgument<string>\]/);
	assert.match(renderedPixels(catalog), /canOmitParameters: false/);
});

test("operation ordering and object insertion order do not change generated bytes", () => {
	const catalog = fresh();
	const reversed = structuredClone(catalog);
	reversed.operations.reverse();
	assert.deepEqual(renderSDK(catalog), renderSDK(reversed));
	assert.equal(
		stableJSON({ z: { b: 1, a: 2 }, a: 3 }),
		stableJSON({ a: 3, z: { a: 2, b: 1 } }),
	);
	assert.deepEqual(
		renderSDK(parseCatalog(stableJSON(catalog))),
		renderSDK(catalog),
	);
});

test("ignore excludes an operation while internal and deprecated coexist", () => {
	const catalog = fresh();
	const op = pixel(catalog).contract;
	op.policy.internalReasons = ["Platform lifecycle only."];
	op.deprecation = {
		deprecated: true,
		since: "6",
		forRemoval: true,
		reason: "Old cancellation API.",
		replacement: "NewCancel",
	};
	assert.match(renderedPixels(catalog), /Internal: Platform lifecycle only/);
	assert.match(
		renderedPixels(catalog),
		/@deprecated Old cancellation API\. Use NewCancel\. Scheduled for removal/,
	);
	op.policy.ignoreReasons = ["Do not expose to clients."];
	assert.doesNotMatch(renderedPixels(catalog), /StopPixelExecution/);
	assert.equal(
		renderSDK(catalog)
			.get("libs/sdk/src/lib/reactors/inventory.ts")
			?.includes("[] as const"),
		true,
	);
	rest(catalog).contract.policy.ignoreReasons = ["Server only."];
	assert.match(
		renderSDK(catalog).get("libs/sdk/src/api/health/health.ts") ?? "",
		/export \{\};/,
	);
});

/** Compile generated contracts with the real builder and consumer type assertions. */
function assertCatalogCompiles(catalog: Catalog, consumer = ""): void {
	const temporary = mkdtempSync(join(tmpdir(), "sdk-catalog-types-"));
	try {
		const roots: string[] = [];
		for (const [path, content] of renderSDK(catalog)) {
			const file = join(temporary, path.replace("libs/sdk/src/", ""));
			mkdirSync(dirname(file), { recursive: true });
			writeFileSync(file, content);
			roots.push(file);
		}
		for (const name of ["build-pixel", "pixel-types", "raw-pixel"]) {
			const file = join(temporary, `lib/${name}.ts`);
			writeFileSync(
				file,
				readFileSync(
					new URL(
						`../../../libs/sdk/src/lib/${name}.ts`,
						import.meta.url,
					),
				),
			);
			roots.push(file);
		}
		const consumerFile = join(temporary, "consumer.ts");
		writeFileSync(consumerFile, consumer);
		roots.push(consumerFile);
		const program = ts.createProgram(roots, {
			target: ts.ScriptTarget.ES2023,
			module: ts.ModuleKind.ESNext,
			moduleResolution: ts.ModuleResolutionKind.Bundler,
			strict: true,
			noEmit: true,
			types: [],
		});
		const diagnostics = ts.getPreEmitDiagnostics(program);
		assert.equal(
			diagnostics.length,
			0,
			ts.formatDiagnosticsWithColorAndContext(diagnostics, {
				getCanonicalFileName: (name) => name,
				getCurrentDirectory: () => temporary,
				getNewLine: () => "\n",
			}),
		);
	} finally {
		rmSync(temporary, { recursive: true, force: true });
	}
}

test("ignoring every selected operation still produces compilable SDK modules", () => {
	const catalog = fresh();
	for (const selected of catalog.operations)
		selected.contract.policy.ignoreReasons = ["Server only."];
	assertCatalogCompiles(catalog);
});

test("buildPixel preserves each generated output type for structured and scalar results", () => {
	const catalog = fresh();
	// This fixture compiles only Pixel consumers; REST transport is tested separately.
	rest(catalog).contract.policy.ignoreReasons = ["Pixel type fixture."];
	const selected = pixel(catalog);
	const count = structuredClone(selected);
	count.name = "CountResult";
	count.contract.source = "fixtures.CountResultReactor";
	count.contract.outputs[0].type = type({
		type: "scalar",
		kind: "INTEGER",
		values: [],
	});
	catalog.operations.push(count);
	selected.contract.outputs[0].type = type({
		type: "reference",
		id: "fixtures.CancellationResult",
	});
	selected.contract.definitions = {
		"fixtures.CancellationResult": {
			id: "fixtures.CancellationResult",
			properties: [
				{ name: "message", required: true, type: string },
				{
					name: "detail",
					required: false,
					type: { ...string, nullable: true },
				},
			],
		},
	};
	assertCatalogCompiles(
		catalog,
		`
import { buildPixel } from "./lib/build-pixel";
import type { BuiltPixel, ResolvePixelOutput } from "./lib/pixel-types";

const cancellation = buildPixel("StopPixelExecution", { id: "job-id" });
const count = buildPixel("CountResult", ["job-id"]);
const branded: BuiltPixel<"StopPixelExecution"> = cancellation;
const expression: string = cancellation;

declare const result: ResolvePixelOutput<typeof cancellation, unknown>;
const message: string = result.message;
const detail: string | null | undefined = result.detail;
// @ts-expect-error The backend declares a record, not a string output.
const wrongOutput: string = result;
// @ts-expect-error Undeclared fields are not part of the output contract.
result.missing;

declare const total: ResolvePixelOutput<typeof count, unknown>;
const amount: number = total;
// @ts-expect-error Each reactor retains its own backend output type.
const wrongCount: typeof result = total;
// @ts-expect-error Serialization does not erase the reactor identity.
const wrongBrand: BuiltPixel<"CountResult"> = cancellation;
`,
	);
});

test("records, collections, maps, unions, wire names and recursive references survive rendering", () => {
	const catalog = fresh();
	const op = pixel(catalog).contract;
	op.outputs[0].type = type({ type: "reference", id: "recursive<wire>" });
	op.definitions = {
		"recursive<wire>": {
			id: "recursive<wire>",
			properties: [
				{
					name: "next-node",
					required: false,
					type: type(
						{ type: "reference", id: "recursive<wire>" },
						{ nullable: true },
					),
				},
				{
					name: "items",
					required: true,
					type: type({
						type: "sequence",
						element: type({
							type: "dictionary",
							value: type({
								type: "union",
								alternatives: [
									string,
									type({
										type: "scalar",
										kind: "INTEGER",
										values: [],
									}),
								],
							}),
						}),
					}),
				},
				{ name: "optional", required: false, type: string },
				{
					name: "nullable",
					required: true,
					type: { ...string, nullable: true, format: "uuid" },
				},
			],
		},
	};
	const source = renderedPixels(catalog);
	assert.match(source, /"next-node"\?: StopPixelExecutionType1 \| null/);
	assert.match(source, /"items": Array<Record<string, string \| number>>/);
	assert.match(source, /"optional"\?: string/);
	assert.match(source, /"nullable": string \| null/);
	assert.match(source, /Wire format: uuid/);
});

test("named aliases, positional order, variadic values and argument omission are distinct", () => {
	const catalog = fresh();
	const op = pixel(catalog).contract;
	assert(op.invocation);
	op.inputs[0].aliases = ["jobId"];
	assert.match(renderedPixels(catalog), /"jobId": PixelArgument<string>/);
	assert.match(renderedPixels(catalog), /"id"\?: PixelArgument<string>/);
	op.inputs[0].requirement = "OPTIONAL";
	assert.match(renderedPixels(catalog), /\[PixelArgument<string>\?\]/);
	assert.match(renderedPixels(catalog), /canOmitParameters: false/);
	op.invocation.canOmitParameters = true;
	assert.match(renderedPixels(catalog), /canOmitParameters: true/);
	op.invocation.variadic = "id";
	assert.match(renderedPixels(catalog), /\.\.\.Array<PixelArgument<string>>/);
	op.inputs[0].requirement = "REQUIRED";
	assert.match(
		renderedPixels(catalog),
		/\[PixelArgument<string>, \.\.\.Array<PixelArgument<string>>\]/,
	);
	op.invocation.order = [];
	assert.throws(() => renderSDK(catalog), /positional order/);
});

test("GET bindings encode path variables and forward optional repeated query values", () => {
	const catalog = fresh();
	const selected = rest(catalog);
	assert(selected.contract.rest);
	selected.contract.rest.path = "/item/{id}/read";
	const base = pixel(catalog).contract.inputs[0];
	selected.contract.inputs = [
		{ ...base, binding: "PATH", aliases: [] },
		{
			...base,
			name: "tag",
			binding: "QUERY",
			requirement: "OPTIONAL",
			type: type({ type: "sequence", element: string }),
			encoding: "REPEATED",
			aliases: [],
		},
	];
	const source =
		renderSDK(catalog).get("libs/sdk/src/api/health/health.ts") ?? "";
	assert.match(source, /path`\/health\/item\/\$\{params\["id"\]\}\/read`/);
	assert.match(source, /"tag": params\["tag"\]/);
	assert.match(source, /"tag"\?: Array<string>/);
	selected.contract.inputs[0].binding = "HEADER";
	assert.throws(() => renderSDK(catalog), /unsupported REST input/);
});

test("unresolved and contradictory contracts fail; explicitly dynamic data remains unknown", () => {
	const catalog = fresh();
	const op = pixel(catalog).contract;
	op.diagnostics = [
		{ severity: "WARNING", source: op.source, message: "Missing @Returns" },
	];
	assert.throws(() => renderSDK(catalog), /Missing @Returns/);
	op.diagnostics = [];
	op.outputs[0].type = type(
		{ type: "unknown" },
		{ knowledge: "UNVERIFIED", reason: "Needs a contract" },
	);
	assert.throws(() => renderSDK(catalog), /unverified type/);
	op.outputs[0].type = type(
		{ type: "unknown" },
		{ knowledge: "DYNAMIC", reason: "Provider-defined output" },
	);
	assert.match(renderedPixels(catalog), /output: unknown/);
	op.outputs[0].type = type({ type: "reference", id: "missing" });
	assert.throws(() => renderSDK(catalog), /Unresolved type reference/);
	assert.throws(
		() => parseCatalog('{"schemaVersion":2,"operations":[]}'),
		/schemaVersion/,
	);
	assert.throws(
		() =>
			parseCatalog(
				snapshot
					.replace('"INTEGER"', '"BAD"')
					.replace('"STRING"', '"BAD"'),
			),
		/Invalid contract value/,
	);
	assert.equal(isGeneratedPath("libs/sdk/src/api/../../env.ts"), false);
	assert.equal(isGeneratedPath("libs/sdk/src/api/auth.ts"), false);
});
